const {JSDOM}=require('jsdom'),assert=require('assert/strict'),fs=require('fs'),path=require('path');
const w=new JSDOM('<main><div class="example"><table><tbody><tr><td id="target">Alfreds Futterkiste</td><td id="other">Maria Anders</td></tr></tbody></table></div></main>',{runScripts:'outside-only'}).window;
w.eval(fs.readFileSync(path.join(__dirname,'../JavaScript/locator-inspector.js'),'utf8'));
const i=w.__seleniumLocatorInspector,td=w.document.querySelector('#target'),other=w.document.querySelector('#other');
const rect=(left,top,right,bottom)=>({left,top,right,bottom,width:right-left,height:bottom-top});
for(const n of w.document.querySelectorAll('*'))n.getBoundingClientRect=()=>rect(0,0,1000,1000);
w.document.head.getBoundingClientRect=()=>rect(0,0,0,0);
td.getBoundingClientRect=()=>rect(100,100,300,140);other.getBoundingClientRect=()=>rect(300,100,500,140);
let checks=0;const check=(ok,msg)=>{assert.ok(ok,msg);checks++};
check(i.findElementsInRectangle(rect(98,98,302,142)).every(n=>n.tagName==='TD'),'small rectangle excludes table, row and page ancestors');
check(i.findElementsInRectangle(rect(120,110,280,130))[0]===td,'rectangle inside cell still selects cell');
check(i.findElementsInRectangle(rect(120,110,480,130)).length===2,'partially enclosed neighboring cells retained');
check(i.findElementsInRectangle(rect(600,600,610,610)).length===1,'empty area chooses smallest intersecting container rather than all ancestors');
const span=w.document.createElement('span');span.textContent='Name';td.appendChild(span);span.getBoundingClientRect=()=>rect(110,105,160,125);
check(!i.findElementsInRectangle(rect(108,103,162,127)).includes(td),'tight child rectangle does not include partial ancestor');
check(i.findElementsInRectangle(rect(98,98,302,142)).includes(td),'fully enclosed cell stays inspectable even with children');
(async()=>{
 let advances=0,closed=false;
 i.flattenMultiFrameDOM=()=>({});
 i.generateLocatorsSteps=function*(){try{for(let k=0;k<30;k++){const until=Date.now()+2;while(Date.now()<until){} advances++;yield;}return {text:'done',candidates:[]};}finally{closed=true;}};
 const job=i.analyseSelection([td],true);let pulses=0;const timer=w.setInterval(()=>pulses++,0);await job;w.clearInterval(timer);
 check(pulses>2&&advances===30,'single element analysis yields between expensive candidate steps');
 check(w.__seleniumLocatorResult.rectangleResults[0].text==='done','cooperative analysis returns complete result');
 advances=0;closed=false;const cancelled=i.analyseSelection([td],true);
 w.setTimeout(()=>i.stopRectangleSelection(),15);await cancelled;
 check(advances<30&&closed,'cancellation closes generator during one element');
 check(w.__seleniumLocatorResult===null,'cancelled job cannot publish');
 w.close();console.log(`Passed ${checks} rectangle selection/cooperative analysis checks.`);
})().catch(e=>{w.close();console.error(e);process.exitCode=1;});
